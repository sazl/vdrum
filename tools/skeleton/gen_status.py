"""Skeleton generator for crates/lxr-core (one-shot: it overwrites the generated stub files, so do not rerun it
after bodies have been ported). Last stage: imports gen_emit (which writes the Rust modules) and writes
docs/PORTING_STATUS.md.

Pipeline, run from this directory with the reference material under /home/user/lxr-ref (outputs stay here):
  python3 -I dwdump.py dw.json                          # DWARF of the reference ELF (lxr_v1.7_gcc11.3.elf)
  python3 -I cg.py cg.json                              # call graph / data refs from the --emit-relocs relocations
  ./compile_o0.sh                                       # -O0 -g objects of files.txt (types/prototypes of every function)
  for o in o0/*.o: python3 -I dwdump.py o0json/<basename of o without .o>.json $o
  ./pp.sh                                               # preprocessed sources (pp/*.i, pp/*.dd)
  python3 -I macros.py && python3 -I probe.py           # #defines and their GCC-evaluated type/value
  python3 -I gen_status.py <repo>/crates/lxr-core       # model.py -> gen.py -> gen_main.py -> gen_emit.py -> this
"""
import sys, os; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_emit import *  # noqa

REPO = os.path.abspath(os.path.join(CRATE, '..', '..'))
ps = []
ps.append('# lxr-core porting status')
ps.append('')
ps.append('Generated by the skeleton generator together with the stubs in `crates/lxr-core`. Every C function of the')
ps.append('engine scope has a stub with its C declaration as doc comment and `todo!("port: file:line")`. When a body is')
ps.append('ported, change its status here from `stub` to `ported` (and to `verified` once it matches the reference).')
ps.append('')
ps.append('Groups: **P1** primitives, **P2** FX (`FxBus.c`, `DSPAudio/FX/**`), **P3** control (MIDI, preset, sequencer,')
ps.append('`Soundengine.c`, `Lxr::new/midi_byte/tick`, hardware/UI externals, non-C helpers), **P4** voices.')
ps.append('')
ps.append('Columns: *Rust* is the path of the stub (`Lxr::f` = method on `Lxr` because the function uses globals).')
ps.append('*Ref build* is how the function exists in `lxr_v1.7_gcc11.3.elf`: `flash`/`itcm` out-of-line symbol, `clone`')
ps.append('(.part/.isra/.constprop), `inlined` (only inlined copies), `gc` (compiled but removed by --gc-sections),')
ps.append('`absent` (file not linked at all, e.g. Reverb, TiltEq, dither, VerbTools, BufferTools, squareRootLut).')
ps.append('Functions marked `gc`/`absent` cannot be checked against the reference binary.')
ps.append('')
cnt = defaultdict(int)
for it in FUNC_ITEMS:
    cnt[it['group']] += 1
ps.append('| Group | Functions |')
ps.append('|---|---|')
for g in sorted(cnt):
    ps.append('| %s | %d |' % (g, cnt[g]))
ps.append('')
ps.append('## Functions')
ps.append('')
ps.append('| C file | C name | Rust | Group | Ref build | Status |')
ps.append('|---|---|---|---|---|---|')
for it in sorted(FUNC_ITEMS, key=lambda i: (i['group'], i['file'], i['line'] or 0)):
    st = 'ported (`src/rng.rs`)' if it['skip'] else ('stub (external)' if it['external'] else 'stub')
    ps.append('| `%s:%s` | `%s` | `%s` | %s | %s | %s |' % (it['file'], it['line'], it['name'], rust_path(it), it['group'], it['link'], st))
ps.append('')
ps.append('## Non-C items')
ps.append('')
ps.append('| Rust | Group | Status | Note |')
ps.append('|---|---|---|---|')
ps.append('| `Lxr::new_zeroed` | - | done | globals with their ELF `.data`/`.dtcm` initial values |')
ps.append('| `Lxr::new` | P3 | stub | power-on init sequence (soundengine_init, preset_init, ...) |')
ps.append('| `Lxr::midi_byte` | P3 | stub | feeds one MIDI byte to the UART MIDI path |')
ps.append('| `Lxr::tick` | P3 | stub | one audio block (sequencer tick + soundengine_calcNextSampleBlock) |')
ps.append('| `Lxr::cptr_read_*` / `Lxr::cptr_write_*` | P3 | stub | resolve a `CPtr` firmware address to an `Lxr` field |')
ps.append('| `fpu::f16_bits_to_f32`, `fpu::f32_to_f16_bits` | P2 | stub | `__fp16` conversions for `FX_BUFFER` |')
ps.append('| `fpu::libm::{expf, logf, exp, fmod, sinf}` | P1 | stub | newlib functions called by engine code |')
ps.append('| `fpu::{fma, vfma, vfms, vfnma, vfnms, *64}`, `fpu::FtzGuard` | - | done | |')
ps.append('| `rng::xorshift32`, `Lxr::GetRngValue` | - | done | xorshift32 13/17/5, seed 0x2545F491 |')
ps.append('| `tables::*` | - | done | generated by `tools/gen_tables.py`, checksum tests |')
ps.append('')
ps.append('## Calls between groups')
ps.append('')
ps.append('A group can only finish a function when its callees in other groups are ported (or stubbed in tests).')
ps.append('')
for g in ['P1', 'P2', 'P3', 'P4']:
    edges = defaultdict(set)
    for it in FUNC_ITEMS:
        if it['group'] != g:
            continue
        for c in it['calls']:
            ci = FUNC_BY_KEY.get(c)
            if ci and ci['group'] != g:
                edges[ci['group']].add((rust_path(ci), it['name']))
    ps.append('### %s calls into other groups' % g)
    ps.append('')
    if not edges:
        ps.append('None.')
        ps.append('')
        continue
    for og in sorted(edges):
        by = defaultdict(set)
        for callee, caller in edges[og]:
            by[callee].add(caller)
        ps.append('* **%s**: %s' % (og, '; '.join('`%s` (from %s)' % (c, ', '.join('`%s`' % x for x in sorted(by[c]))) for c in sorted(by))))
    ps.append('')
os.makedirs(REPO + '/docs', exist_ok=True)
open(REPO + '/docs/PORTING_STATUS.md', 'w').write('\n'.join(ps) + '\n')
print('wrote', REPO + '/docs/PORTING_STATUS.md')
