#!/usr/bin/env python3
"""Generate crates/lxr-core/src/fpu/libm/tables.rs from the shipped v1.71 firmware binary.

usage: python3 -I tools/gen_libm_tables.py <lxr_v1.71_shipped.bin | LXRV2_update_v1.71.img> <out.rs> [<lxr_v1.7_gcc11.3.elf>]

The data tables (`__exp_data`, `__exp2f_data`, `__logf_data`, the `Zero[]` table of `__ieee754_fmod`) and the
literal pool constants of the libm functions are read from the shipped binary (loaded at 0x08008000) at the
addresses found by disassembling it (the shipped binary has no symbols; the functions were located through the
BL call sites in Compressor_setAttack / Compressor_process / Distortion_process, whose shipped addresses are in
function_match_v1.71_vs_gcc11.json). If the GCC 11.3 reference ELF is given, every table and constant is also
compared with the ELF (tables by symbol, constants by their literal pool address) and the script fails on any
difference. Nothing is retyped.
"""
import struct
import sys

BASE = 0x08008000

# (rust name, shipped address, number of u64 words, ELF symbol or ELF address)
TABLES = [
    ('EXP_DATA', 0x0803D4E0, 270, '__exp_data', '`__exp_data` (exp.c, EXP_TABLE_BITS = 7, EXP_POLY_ORDER = 5)'),
    ('EXP2F_DATA', 0x0803DD50, 41, '__exp2f_data', '`__exp2f_data` (expf.c, EXP2F_TABLE_BITS = 5)'),
    ('LOGF_DATA', 0x0803DE98, 36, '__logf_data', '`__logf_data` (logf.c, LOGF_TABLE_BITS = 4)'),
    ('FMOD_ZERO', 0x0803DFB8, 2, 0x0803E378, '`Zero[] = {0.0, -0.0}` of e_fmod.c'),
]

# (rust name, rust type, shipped literal address, ELF literal address, doc)
CONSTS = [
    ('EXP_SPECIAL_POS_SCALE', 'f64', 0x080297D0, 0x080297E8, 'exp specialcase: 0x1p1009'),
    ('EXP_SPECIAL_NEG_SCALE', 'f64', 0x080297D8, 0x080297E0, 'exp specialcase: 0x1p-1022'),
    ('EXP_SPECIAL_ZERO', 'f64', 0x080297E0, 0x080297F0, 'exp specialcase / exp(-inf): 0.0'),
    ('MATH_UFLOW', 'f64', 0x08029830, 0x08029840, '__math_uflow: 0x1p-767'),
    ('MATH_OFLOW', 'f64', 0x08029840, 0x08029850, '__math_oflow: 0x1p769'),
    ('MATH_CHECK_OFLOW_MAX', 'f64', 0x08029880, 0x08029890, '__math_check_oflow: DBL_MAX'),
    ('EXPF_OFLOW_BOUND', 'f32', 0x0802995C, 0x0802996C, 'expf: 0x1.62e42ep6f'),
    ('EXPF_UFLOW_BOUND', 'f32', 0x08029960, 0x08029970, 'expf: -0x1.9fe368p6f'),
    ('EXPF_MAY_UFLOW_BOUND', 'f32', 0x08029964, 0x08029974, 'expf: -0x1.9d1d9ep6f'),
    ('EXPF_ZERO', 'f32', 0x0802996C, 0x08029978, 'expf(-inf): 0.0f'),
    ('LOGF_SUBNORMAL_SCALE', 'f32', 0x08029A30, 0x08029A40, 'logf: 0x1p23f'),
    ('LOGF_ZERO', 'f32', 0x08029A38, 0x08029A3C, 'logf(1): 0.0f'),
    ('MATH_UFLOWF', 'f32', 0x08029A70, 0x08029AD8, '__math_uflowf: 0x1p-95f'),
    ('MATH_MAY_UFLOWF', 'f32', 0x08029A7C, 0x08029AE4, '__math_may_uflowf: 0x1.4p-75f'),
    ('MATH_OFLOWF', 'f32', 0x08029A88, 0x08029AF0, '__math_oflowf: 0x1p97f'),
    ('MATH_DIVZEROF_ZERO', 'f32', 0x08029AAC, 0x08029B14, '__math_divzerof: 0.0f'),
    ('FMOD_WRAPPER_ZERO', 'f64', 0x08029640, 0x08029A90, 'fmod wrapper: 0.0 (returns 0.0/0.0 for y == 0)'),
]


def fnv1a64(data):
    h = 0xcbf29ce484222325
    for b in data:
        h ^= b
        h = (h * 0x100000001b3) & 0xffffffffffffffff
    return h


class Elf:
    def __init__(self, path):
        self.d = open(path, 'rb').read()
        d = self.d
        assert d[:4] == b'\x7fELF' and d[4] == 1, 'expected ELF32'
        phoff, = struct.unpack_from('<I', d, 0x1c)
        shoff, = struct.unpack_from('<I', d, 0x20)
        phentsize, phnum, shentsize, shnum, shstrndx = struct.unpack_from('<HHHHH', d, 0x2a)
        self.segs = []
        for i in range(phnum):
            t, off, va, pa, fsz, msz, fl, al = struct.unpack_from('<8I', d, phoff + i * phentsize)
            if t == 1:
                self.segs.append((va, off, fsz))
        secs = [struct.unpack_from('<10I', d, shoff + i * shentsize) for i in range(shnum)]
        self.syms = {}
        for s in secs:
            if s[1] == 2:  # SHT_SYMTAB
                strtab = secs[s[6]]
                for j in range(s[5] // 16):
                    name, value, size, info, other, shndx = struct.unpack_from('<IIIBBH', d, s[4] + 16 * j)
                    o = strtab[4] + name
                    n = d[o:d.index(b'\0', o)].decode()
                    self.syms.setdefault(n, (value, size))

    def read(self, a, n):
        for va, off, fsz in self.segs:
            if va <= a and a + n <= va + fsz:
                return self.d[off + a - va: off + a - va + n]
        raise KeyError(hex(a))


def main():
    src, out = sys.argv[1], sys.argv[2]
    data = open(src, 'rb').read()
    if data[:8] == b'LXRV2IMG':
        data = data[16:]
    elf = Elf(sys.argv[3]) if len(sys.argv) > 3 else None

    def ship(a, n):
        b = data[a - BASE: a - BASE + n]
        assert len(b) == n
        return b

    lines = [
        '// @generated by tools/gen_libm_tables.py from the shipped v1.71 binary (lxr_v1.71_shipped.bin, base',
        '// 0x08008000). Do not edit. Tables and literal pool constants of the newlib libm functions that the',
        '// engine calls; identical in the GCC 11.3 reference ELF (checked by the generator).',
        '',
    ]
    for name, addr, words, elf_ref, doc in TABLES:
        b = ship(addr, words * 8)
        if elf:
            ea = elf.syms[elf_ref][0] if isinstance(elf_ref, str) else elf_ref
            if isinstance(elf_ref, str):
                assert elf.syms[elf_ref][1] == words * 8, (name, elf.syms[elf_ref])
            assert elf.read(ea, words * 8) == b, f'{name} differs from the ELF'
        vals = struct.unpack(f'<{words}Q', b)
        lines.append(f'/// {doc}: {words * 8} bytes at {addr:#010x} in the shipped binary, as little endian u64 words')
        lines.append(f'/// (index = byte offset / 8, as addressed by the machine code). FNV-1a 64: {fnv1a64(b):#018x}.')
        lines.append(f'pub static {name}: [u64; {words}] = [')
        for i in range(0, words, 4):
            lines.append('    ' + ' '.join(f'0x{v:016x},' for v in vals[i:i + 4]))
        lines.append('];')
        lines.append('')
    for name, ty, addr, elf_addr, doc in CONSTS:
        n = 8 if ty == 'f64' else 4
        b = ship(addr, n)
        if elf:
            assert elf.read(elf_addr, n) == b, f'{name} differs from the ELF'
        v = int.from_bytes(b, 'little')
        width = 16 if ty == 'f64' else 8
        lines.append(f'/// {doc} (literal pool at {addr:#010x}).')
        lines.append(f'pub const {name}: {ty} = {ty}::from_bits(0x{v:0{width}x});')
    lines.append('')
    open(out, 'w').write('\n'.join(lines))


if __name__ == '__main__':
    main()
